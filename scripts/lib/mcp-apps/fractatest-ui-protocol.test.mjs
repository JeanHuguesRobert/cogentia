import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('./fractatest.html',import.meta.url),'utf8');
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
test('MCP Apps v2 sends a proper initialization and signals ready only after host response',()=>{
 assert.ok(js);
 const outgoing=[];
 const parent={postMessage:(value)=>outgoing.push(value)};
 const listeners={};
 const elements=Object.fromEntries(['toggle','invariants','message'].map(id=>[id,{hidden:id==='invariants',textContent:'',addEventListener(type,fn){this[type]=fn},setAttribute(){}}]));
 const context={window:{parent,addEventListener(type,fn){listeners[type]=fn}},document:{getElementById:id=>elements[id]},Object};
 vm.runInNewContext(js,context,{timeout:1000});
 assert.equal(outgoing.length,1);
 assert.equal(outgoing[0].method,'ui/initialize');
 assert.equal(outgoing[0].params.protocolVersion,'2026-01-26');
 assert.deepEqual(Array.from(outgoing[0].params.appCapabilities.availableDisplayModes),['inline']);
 listeners.message({source:{},data:{jsonrpc:'2.0',id:outgoing[0].id,result:{protocolVersion:'2026-01-26'}}});
 assert.equal(outgoing.length,1,'ignored foreign-frame message');
 listeners.message({source:parent,data:{jsonrpc:'2.0',id:outgoing[0].id,result:{protocolVersion:'2026-01-26'}}});
 assert.equal(outgoing[1].method,'ui/notifications/initialized');
 listeners.message({source:parent,data:{jsonrpc:'2.0',id:outgoing[0].id,result:{protocolVersion:'2026-01-26'}}});
 assert.equal(outgoing.length,2,'no duplicate initialized notifications');
 elements.toggle.click();assert.equal(elements.invariants.hidden,false);
 listeners.message({source:parent,data:{jsonrpc:'2.0',id:48,method:'ui/resource-teardown',params:{}}});
 assert.equal(outgoing.at(-1).id,48);
 assert.equal(Object.keys(outgoing.at(-1).result).length,0);
});
